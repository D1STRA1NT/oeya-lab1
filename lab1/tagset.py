"""Теги задания и их соответствие разметке Universal Dependencies.

Модуль описывает набор тегов лабораторной работы (S, A, V, ADV, PR, CONJ, NI и другие)
и правила, по которым части речи корпуса и словаря приводятся к этим тегам.
Все правила разметки собраны здесь, чтобы их можно было быстро подстроить под
требования проверяющего.
"""

# для словаря словоформ
TAGS = ["S", "A", "V", "ADV", "PR", "CONJ", "NI", "NUM", "INTJ", "UNKN"]
TAG_ID = {tag: index for index, tag in enumerate(TAGS)}

# части речи корпуса Universal Dependencies и соответствующие им теги задания
UPOS_TO_TAG = {
    # существительные:  нариц и собств
    "NOUN": "S",
    "PROPN": "S",

    # прилагательные
    "ADJ": "A",

    # глаголы: осн и вспом
    "VERB": "V",
    "AUX": "V",

    # наречия и частицы
    "ADV": "ADV",
    "PART": "ADV",

    # предлоги
    "ADP": "PR",

    # союзы: сочинительные и подчинительные
    "CCONJ": "CONJ",
    "SCONJ": "CONJ",

    # местоимения: собств и неопред
    "PRON": "NI",
    "DET": "NI",

    # числительные
    "NUM": "NUM",

    # междометия
    "INTJ": "INTJ",

    # прочее: слова с пометкой Foreign=Yes - facebook, bluetooth и латынь
    "X": "UNKN",
}
# знаки препинания и символы в ответе не нужны
SKIP_UPOS = frozenset({"PUNCT", "SYM"})

# части речи словаря UniMorph, там описаны только изменяемые слова
UNIMORPH_TO_TAG = {
    "N": "S",
    "ADJ": "A",
    "V": "V",
    # причастие и деепричастие
    "V.PTCP": "V",
    "V.CVB": "V",
}


def tag_from_upos(upos: str) -> str | None:
    """Находит тег задания по части речи Universal Dependencies.

    Args:
        upos: Часть речи из третьего признака разметки, например NOUN.

    Returns:
        Тег задания или None, если слово нужно пропустить или часть речи неизвестна.
    """
    return UPOS_TO_TAG.get(upos)
